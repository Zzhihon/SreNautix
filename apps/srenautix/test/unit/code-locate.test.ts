import { createHash } from 'node:crypto';
import { describe, expect, it } from 'vitest';
import { optimizationConfig } from '../../src/optimize/config.js';
import { codeExcerpts, codeFiles, locateCode, pathLabels } from '../../src/optimize/code/locate.js';
import { RepoCodeCache, type GitHubReader } from '../../src/optimize/code/tree.js';

// 代码定位（ADR 0146 §3.5）：目录树缓存、范围收缩、读取上限、sql 指纹与表名、字面量、生成代码的调用方、片段脱敏

const REPO = 'CCH-HQ/claude-code-hub-plus';
const COMMIT = 'a'.repeat(40);

const FILES: Record<string, string> = {
  'internal/usage/store.go': `package usage

type Store struct{ db DB }

func (s *Store) Recent(org string) error {
	_, err := s.db.Query(\`SELECT id, cost FROM usage_logs WHERE org_id = $1 ORDER BY created_at DESC LIMIT 50\`, org)
	return err
}

func (s *Store) Count(org string) error {
	_, err := s.db.Query("SELECT count(*) FROM usage_logs WHERE org_id = $1", org)
	return err
}
`,
  'internal/db/queries.sql.go': `// Code generated by sqlc. DO NOT EDIT.
package db

const getKey = \`-- name: GetKey :one
SELECT id, secret_hash FROM api_keys WHERE id = $1
\`

func (q *Queries) GetKey(ctx context.Context, id string) (Key, error) {
	row := q.db.QueryRow(ctx, getKey, id)
	return scan(row)
}
`,
  'internal/auth/check.go': `package auth

func (a *Auth) Verify(ctx context.Context, id string) error {
	k, err := a.q.GetKey(ctx, id)
	_ = k
	return err
}
`,
  'internal/gateway/stage.go': `package gateway

func plan() {
	tracer.Start(ctx, "cchp.gateway.stage.plan")
}
`,
  'internal/usage/store_test.go': `package usage
var x = "SELECT id, cost FROM usage_logs WHERE org_id = $1"
`,
  'web/src/poll.ts': `export const poll = () => fetch('/v1/status');
`,
  'db/migrations/001.sql': `CREATE TABLE usage_logs (id bigint);
SELECT id, cost FROM usage_logs WHERE org_id = $1 ORDER BY created_at DESC LIMIT 50;
`,
  'docs/readme.md': 'x',
  'config/.env.prod': 'SECRET=1',
};

const blobSha = (p: string) =>
  createHash('sha1')
    .update(FILES[p] as string)
    .digest('hex');

function fakeGitHub() {
  const calls: string[] = [];
  const gh: GitHubReader = {
    api: async <T>(method: string, path: string): Promise<T> => {
      calls.push(`${method} ${path}`);
      if (path.startsWith(`/repos/${REPO}/git/trees/${COMMIT}`)) {
        return {
          sha: COMMIT,
          truncated: false,
          tree: [
            { path: 'internal', type: 'tree', sha: 'b'.repeat(40) },
            ...Object.keys(FILES).map((p) => ({
              path: p,
              type: 'blob',
              sha: blobSha(p),
              size: (FILES[p] as string).length,
            })),
          ],
        } as T;
      }
      const m = new RegExp(`^/repos/${REPO}/contents/(.+)\\?ref=${COMMIT}$`).exec(path);
      if (m) {
        const p = decodeURIComponent(m[1] as string);
        return {
          type: 'file',
          sha: blobSha(p),
          size: (FILES[p] as string).length,
          encoding: 'base64',
          content: Buffer.from(FILES[p] as string).toString('base64'),
        } as T;
      }
      throw new Error(`unexpected ${method} ${path}`);
    },
  };
  return { gh, calls };
}

/** 测试用的指纹：去掉注释、常量与空白差异后小写（真实实现是 libpg-query 的 fingerprint） */
const fingerprint = (sql: string) =>
  sql
    .replace(/--[^\n]*/g, ' ')
    .replace(/\$\d+|'[^']*'|\b\d+\b/g, '?')
    .replace(/\s+/g, ' ')
    .trim()
    .replace(/;$/, '')
    .toLowerCase();

const repository = optimizationConfig.parse({
  repositories: {
    business: {
      repo: REPO,
      default_branch: 'dev',
      code: {
        version: { rule: 'default_branch' },
        root: '',
        include: ['**/*.go', '**/*.ts', '**/*.tsx', '**/*.sql'],
        exclude: [],
        languages: ['go', 'typescript'],
        anchors: [
          { kind: 'sql', paths: ['internal/**', 'db/**'] },
          { kind: 'table', paths: ['internal/**', 'db/**'] },
          { kind: 'span_name', paths: ['internal/gateway/**'] },
        ],
        labels: [
          { paths: ['internal/usage/**'], label: 'area/usage' },
          { paths: ['internal/gateway/**'], label: 'area/gateway' },
        ],
      },
    },
  },
}).repositories.business!;
const layout = repository.code;

describe('代码定位', () => {
  it('候选文件：包含与排除规则，测试文件、文档与 .env 不读', () => {
    const entries = Object.keys(FILES).map((p) => ({ path: p, sha: blobSha(p), size: 1 }));
    expect(codeFiles(entries, layout).map((e) => e.path)).toEqual([
      'internal/usage/store.go',
      'internal/db/queries.sql.go',
      'internal/auth/check.go',
      'internal/gateway/stage.go',
      'web/src/poll.ts',
      'db/migrations/001.sql',
    ]);
  });

  it('sql：指纹相等为高置信度并给出方法与接收者；只有表名命中为低；.sql 文件按语句匹配', async () => {
    const { gh } = fakeGitHub();
    const cache = new RepoCodeCache(gh);
    const r = await locateCode(
      repository,
      COMMIT,
      [
        { kind: 'sql', value: 'SELECT id, cost FROM usage_logs WHERE org_id = $1 ORDER BY created_at DESC LIMIT $2' },
        { kind: 'table', value: 'public.usage_logs' },
      ],
      { cache, fingerprint },
    );
    expect(r.locations.map((l) => [l.path, l.symbol, l.receiver, l.match_kind, l.confidence, l.line])).toEqual([
      ['db/migrations/001.sql', null, null, 'sql_fingerprint', 'high', 2],
      ['internal/usage/store.go', 'Recent', 'Store', 'sql_fingerprint', 'high', 6],
      ['internal/usage/store.go', 'Count', 'Store', 'sql_table', 'low', 11],
    ]);
    expect(r.locations[1]).toMatchObject({ repository: REPO, commit: COMMIT, start_line: 5, end_line: 8 });
    // 范围收缩：web/ 不在 sql 锚点规则内，不读取
    expect([...r.contents.keys()]).not.toContain('web/src/poll.ts');
    const paths = r.locations.map((l) => l.path);
    expect(pathLabels(layout, paths)).toEqual(['area/usage']);
  });

  it('命中生成代码时按生成的函数名再找一层调用方，置信度降一档', async () => {
    const { gh } = fakeGitHub();
    const r = await locateCode(
      repository,
      COMMIT,
      [{ kind: 'sql', value: 'SELECT id, secret_hash FROM api_keys WHERE id = $1' }],
      { cache: new RepoCodeCache(gh), fingerprint },
    );
    expect(r.locations.map((l) => [l.path, l.symbol, l.match_kind, l.confidence])).toEqual([
      ['internal/db/queries.sql.go', 'getKey', 'sql_fingerprint', 'high'],
      ['internal/auth/check.go', 'Verify', 'caller', 'medium'],
    ]);
  });

  it('字面量精确匹配为中置信度；目录树与内容按提交与 blob 缓存', async () => {
    const { gh, calls } = fakeGitHub();
    const cache = new RepoCodeCache(gh);
    const anchors = [{ kind: 'span_name' as const, value: 'cchp.gateway.stage.plan' }];
    const r = await locateCode(repository, COMMIT, anchors, { cache, fingerprint });
    expect(r.locations).toMatchObject([
      { path: 'internal/gateway/stage.go', symbol: 'plan', match_kind: 'literal', confidence: 'medium', line: 4 },
    ]);
    const n = calls.length;
    await locateCode(repository, COMMIT, anchors, { cache, fingerprint });
    expect(calls.length).toBe(n);
    expect(calls.filter((c) => c.includes('/git/trees/'))).toHaveLength(1);
  });

  it('读取上限：超过文件数时只读按路径排序的前几个，并写明', async () => {
    const { gh } = fakeGitHub();
    const r = await locateCode(
      repository,
      COMMIT,
      [{ kind: 'sql', value: 'SELECT 1' }],
      { cache: new RepoCodeCache(gh), fingerprint },
      { maxFiles: 2 },
    );
    expect(r.read.files).toBe(2);
    expect(r.notes.join('')).toMatch(/超过读取上限/);
  });

  it('片段：命中行前后各 20 行，带行号，经脱敏', () => {
    const text = [...Array.from({ length: 30 }, (_, i) => `line ${i + 1}`), 'key := "AKIAIOSFODNN7EXAMPLE"'].join('\n');
    const [e] = codeExcerpts(new Map([['a.go', text]]), [
      {
        repository: REPO,
        commit: COMMIT,
        path: 'a.go',
        start_line: 25,
        end_line: 31,
        line: 25,
        symbol: 'f',
        receiver: null,
        anchor: 'sql',
        match_kind: 'sql_fingerprint',
        confidence: 'high',
      },
    ]);
    expect(e?.text.split('\n')[0]).toBe('    5  line 5');
    expect(e?.text.split('\n')).toHaveLength(27);
    expect(e?.text).not.toContain('AKIAIOSFODNN7EXAMPLE');
    expect(e?.redactions).toBeGreaterThan(0);
  });
});
