export const OPTIMIZE_PROMPTS: Readonly<Record<Language, OptimizePromptSet>> = { zh, en };

/** 提示词模板的哈希，按阶段写入运行清单 */
export function optimizePromptHash(language: Language, step: 'hypothesize' | 'conclude'): string {
  const p = OPTIMIZE_PROMPTS[language];
  return `sha256:${createHash('sha256').update(`${p.system}\0${p[step]}`).digest('hex')}`;
}
